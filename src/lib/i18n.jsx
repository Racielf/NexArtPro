const LanguageContext = createContext(null);

function interpolate(message, values) {
  return Object.entries(values || {}).reduce(
    (result, [key, value]) => result.replaceAll(`{${key}}`, String(value)),
    message,
  );
}

export function LanguageProvider({ children }) {
  const [language, setLanguageState] = useState(() => {
    const stored = localStorage.getItem(APP_LANGUAGE_STORAGE_KEY);
    return SUPPORTED_LANGUAGES.some((item) => item.code === stored) ? stored : 'es';
  });

  const setLanguage = (nextLanguage) => {
    if (!SUPPORTED_LANGUAGES.some((item) => item.code === nextLanguage)) return;
    localStorage.setItem(APP_LANGUAGE_STORAGE_KEY, nextLanguage);
    setLanguageState(nextLanguage);
  };

  useEffect(() => {
    document.documentElement.lang = language;
  }, [language]);

  const value = useMemo(() => ({
    language,
    setLanguage,
    languages: SUPPORTED_LANGUAGES,
    t: (key, values) => interpolate(messages[language]?.[key] || messages.es[key] || key, values),
  }), [language]);

  return <LanguageContext.Provider value={value}>{children}</LanguageContext.Provider>;
}

export function useLanguage() {
  const context = useContext(LanguageContext);
  if (!context) throw new Error('useLanguage must be used inside LanguageProvider');
  return context;
}
